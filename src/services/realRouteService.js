/**
 * Dynamically fetch real road geometry from OSRM for any arbitrary pair of coordinates
 */
export async function fetchOsrmRoadPath(waypoints) {
  if (!waypoints || waypoints.length < 2) return null;
  try {
    const coordStr = waypoints.map(([lat, lng]) => `${lng},${lat}`).join(';');
    const response = await fetch(`https://router.project-osrm.org/route/v1/driving/${coordStr}?overview=full&geometries=geojson`);
    if (!response.ok) return null;
    const data = await response.json();
    if (data.routes && data.routes[0]) {
      const raw = data.routes[0].geometry.coordinates;
      const step = Math.max(1, Math.floor(raw.length / 300));
      const sampled = [];
      for (let i = 0; i < raw.length; i += step) {
        sampled.push([Number(raw[i][1].toFixed(4)), Number(raw[i][0].toFixed(4))]);
      }
      if (raw.length > 0) {
        const last = raw[raw.length - 1];
        sampled.push([Number(last[1].toFixed(4)), Number(last[0].toFixed(4))]);
      }
      return sampled;
    }
  } catch (err) {
    console.warn('OSRM live fetch fallback:', err.message);
  }
  return null;
}

